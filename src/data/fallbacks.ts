/** Google Maps search URL for a school's coordinates. */
export function mapsUrl(s: { lat?: any; lng?: any }) {
  return `https://www.google.com/maps/search/?api=1&query=${s.lat},${s.lng}`;
}

/** True when a school has both coordinates entered, so a map link makes sense. */
export function hasCoords(s: { lat?: any; lng?: any }) {
  return s.lat != null && s.lng != null && s.lat !== "" && s.lng !== "";
}
